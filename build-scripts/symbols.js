var fs = require('fs')
var path = require('path')

// the C library symbols, read from libsodium.js (all of libsodium compiled to wasm, it exports every function)
var sodiumJs = path.dirname(require.resolve('sodium-js/package.json'))
var wrappers = require.resolve('libsodium-wrappers-sumo', { paths: [sodiumJs] })
var libsodiumFile = require.resolve('libsodium-sumo', { paths: [wrappers] })
var libsodium = fs.readFileSync(libsodiumFile, 'utf8')
var symbols = [...new Set(libsodium.match(/\b_(crypto|randombytes|sodium)_\w+/g))].sort()
var native = new Set(Object.keys(require('sodium-native')).sort())
var js = new Set(Object.keys(require('sodium-js/browser.js')).sort())

symbols = symbols.map((l) => l.replace(/^_/, '').replace(/_[^_]*bytes.*/, (s) => s.toUpperCase()))

var missing = []

console.log(`
<!-- Generated by build-scripts/symbols.js with
     sodium-native@${require('sodium-native/package.json').version}
     sodium-js@${require('sodium-js/package.json').version}
     libsodium-sumo@${require(path.join(path.dirname(libsodiumFile), '../../package.json')).version} -->\
`)

const max = symbols
  .filter((s) => native.has(s) || js.has(s))
  .map((s) => s.length)
  .reduce((a, b) => Math.max(a, b))
const lines = ':-' + ''.padEnd(max, '--') + '-:'
const center = (s) => s.padStart(Math.floor((max + s.length) / 2), ' ').padEnd(max, ' ')

console.log(`|  ${center('C Library Symbol')}  |   \`sodium-native\`    |     \`sodium-js\`      |`)
console.log(`|${lines}|:--------------------:|:--------------------:|`)

for (var i = 0; i < symbols.length; i++) {
  var s = symbols[i]
  if (!(native.has(s) || js.has(s))) missing.push(s)
  else {
    console.log(
      `| \`${(s + '`').padEnd(max + 1, ' ')} | ${native.has(s) ? ' :white_check_mark: ' : ':small_red_triangle:'} | ${js.has(s) ? ' :white_check_mark: ' : ':small_red_triangle:'} |`
    )
  }
}

console.log('\n### Missing altogether (Ctrl + F friendly)\n')
console.log(missing.map((s) => '`' + s + '`').join(', '))
